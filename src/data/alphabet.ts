export function getLetterForms(letter: ArabicLetter) {
  const TATWEEL = 'ـ'
  if (!letter.connectsToNext) {
    return {
      isolated: letter.char,
      final: TATWEEL + letter.char,
      initial: null,
      medial: null,
    }
  }
  return {
    isolated: letter.char,
    initial: letter.char + TATWEEL,
    medial: TATWEEL + letter.char + TATWEEL,
    final: TATWEEL + letter.char,
  }
}
